import BigNumber from 'bignumber.js';
import type { PrismaClient } from '@prisma/client';
import type { PrivateTradingService } from '../service';
import type { OwnerSession } from '../serviceTypes';
import { NativeDemoService } from './service';
import { PrismaNativeRepository } from './store';
import { demoPositionView, type DemoState } from './engine';
import { isHistory20Contract } from './history20Contract';

/**
 * What a Cross trading account can withdraw, per asset, from one valuation:
 * the `available` of the same wallet rows the Wallet page prints (the row's
 * own margin in use already taken out). The settle asset is further capped
 * by the account's `available` — its free margin — so a request can never
 * claim margin that backs an open position. `null` when the account has not
 * been opened.
 *
 * `undefined` without market data: no valuation is possible, and those
 * accounts then withdraw from the spot ledger like everyone else.
 *
 * A gain made on a History20 model contract is generated by a modeled price
 * path, not earned against a market: it never becomes withdrawable. The net
 * realized result of those contracts, when positive, is held back from the
 * settle asset (losses already reduce it). Every other figure is unchanged.
 */
export function nativeWithdrawableRows(prisma: PrismaClient, service: PrivateTradingService) {
  if (!service.market) return undefined;
  const repository = new PrismaNativeRepository(prisma, service.store?.config);
  const native = new NativeDemoService(repository, service.market);
  return async (actor: OwnerSession) => {
    // Read around the valuation: a trade between the reads holds back the larger figure.
    const before = await repository.read(actor);
    const wallet = await native.wallet(actor);
    if (!wallet) return null;
    const after = await repository.read(actor);
    const held = BigNumber.max(history20Gains(before?.snapshot), history20Gains(after?.snapshot)).toFixed();
    return withdrawableRows(wallet, held);
  };
}

/** The positive net realized result (price, fees, funding) of History20 model contracts; '0' without any. */
export function history20Gains(state: DemoState | null | undefined): string {
  if (!state) return '0';
  const net = state.positions.filter(p => isHistory20Contract(p.symbol))
    .reduce((sum, p) => sum.plus(demoPositionView(state, p).realizedPnl), new BigNumber(0));
  return BigNumber.max(net, 0).toFixed();
}

/** The projection itself, apart from the valuation that feeds it. */
export function withdrawableRows(wallet: {
  account: { available: string };
  collateral: { settleAsset: string };
  rows: { asset: string; available: string }[];
}, heldGains = '0'): { asset: string; available: string }[] {
  const settle = wallet.collateral.settleAsset;
  return wallet.rows.map((row) => ({
    asset: row.asset,
    available: row.asset === settle
      ? BigNumber.max(BigNumber.min(row.available, wallet.account.available).minus(heldGains), 0).toFixed()
      : row.available,
  }));
}
